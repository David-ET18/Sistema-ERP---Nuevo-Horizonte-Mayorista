-- ----------------------------------------------------------------------------
-- promocion: ahora vive en catalogo.
-- Si una BD vieja la tiene en promociones, se mueve conservando sus datos.
-- Si no existe en ningun lado, se crea en catalogo.
-- ----------------------------------------------------------------------------
DO $migracion$
BEGIN
    IF to_regclass('catalogo.promocion') IS NULL THEN
        IF to_regclass('promociones.promocion') IS NOT NULL THEN
            ALTER TABLE promociones.promocion SET SCHEMA catalogo;
        ELSE
            CREATE TABLE catalogo.promocion (
                id_promocion bigint GENERATED BY DEFAULT AS IDENTITY,
                activa boolean DEFAULT true NOT NULL,
                descripcion text,
                descuento_porcentaje numeric(5,2) NOT NULL,
                destacada boolean DEFAULT false NOT NULL,
                fecha_actualizacion timestamp(6) without time zone NOT NULL,
                fecha_creacion timestamp(6) without time zone NOT NULL,
                fecha_fin date,
                fecha_inicio date,
                imagen bytea,
                imagen_nombre character varying(200),
                imagen_tipo character varying(100),
                nombre character varying(120) NOT NULL,
                id_servicio bigint,
                imagen_content_type character varying(60),
                imagen_tamano bigint,
                precio_original numeric(10,2),
                precio_promocional numeric(10,2),
                CONSTRAINT promocion_pkey PRIMARY KEY (id_promocion),
                CONSTRAINT fk_promocion_servicio FOREIGN KEY (id_servicio)
                    REFERENCES catalogo.servicio (id_servicio)
                    ON DELETE SET NULL
            );
        END IF;
    END IF;
END
$migracion$;