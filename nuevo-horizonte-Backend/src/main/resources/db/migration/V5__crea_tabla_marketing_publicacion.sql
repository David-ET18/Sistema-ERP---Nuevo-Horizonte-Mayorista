-- V5: historial de publicaciones del modulo de difusion y marketing
CREATE SCHEMA IF NOT EXISTS marketing;

CREATE TABLE IF NOT EXISTS marketing.publicacion (
    id_publicacion bigint GENERATED BY DEFAULT AS IDENTITY,
    texto_original text NOT NULL,
    texto_publicado text,
    canal character varying(20) NOT NULL DEFAULT 'TELEGRAM',
    estado character varying(20) NOT NULL,
    mensaje_error text,
    imagen bytea,
    imagen_content_type character varying(60),
    imagen_nombre character varying(200),
    imagen_tamano bigint,
    responsable_username character varying(50),
    responsable_nombre character varying(100),
    fecha_publicacion timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT publicacion_pkey PRIMARY KEY (id_publicacion)
);
